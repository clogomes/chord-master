"""Musical Glossary module providing definitions, formulas, instrument examples, and audio playback notes."""
import unicodedata
from dataclasses import dataclass, field
from typing import Dict, List, Optional
from core.notes import Note


@dataclass
class GlossaryTerm:
    id: str
    term_pt: str
    term_en: str
    category: str  # "harmonia", "ritmo", "notacao", "tecnica", "acustica", "forma", "jazz", "modos"
    short_def_pt: str
    short_def_en: str
    long_def_pt: str
    long_def_en: str
    formula: Optional[str] = None
    example_piano: Optional[str] = None
    example_guitar: Optional[str] = None
    hear_it: List[str] = field(default_factory=list)  # Pitches to synthesize
    see_also: List[str] = field(default_factory=list)  # Term IDs
    chapters: List[str] = field(default_factory=list)  # Chapter IDs

    def get_term(self, lang: str = "pt") -> str:
        return self.term_en if lang == "en" and self.term_en else self.term_pt

    def get_short_def(self, lang: str = "pt") -> str:
        return self.short_def_en if lang == "en" and self.short_def_en else self.short_def_pt

    def get_long_def(self, lang: str = "pt") -> str:
        return self.long_def_en if lang == "en" and self.long_def_en else self.long_def_pt


